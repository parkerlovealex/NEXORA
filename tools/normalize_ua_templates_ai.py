#!/usr/bin/env python3
"""Use Cerebras AI to propose slot-normalized UA templates from decoded rows.

AI is constrained to candidate/pending output. Source metadata and raw strings
are attached by code, not generated by the model. Deterministic validation is
still required and the AI can never mark a record verified.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.request
from datetime import date, datetime, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_ua_templates as validator

API_URL = "https://api.cerebras.ai/v1/chat/completions"
DEFAULT_MODEL = "llama-3.3-70b"


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")[:70] or "row"


def allowed_slot_paths(app: str) -> list[str]:
    return [
        "device.brand", "device.model", "device.uaModel", "device.id",
        "device.codename", "device.soc", "device.osVersions[]",
        "device.builds[osVersion]", "device.display.w", "device.display.h",
        "device.display.dpr", "device.display.ppi", "meta.versions.chrome",
        f"meta.apps.{app}.version", f"meta.apps.{app}.build",
        f"meta.apps.{app}.versions[].version", f"meta.apps.{app}.versions[].build",
    ]


def ai_request(rows: list[dict[str, Any]], devices: dict[str, Any], api_key: str, model: str = DEFAULT_MODEL) -> dict[str, Any]:
    app_keys = sorted((devices.get("meta", {}).get("apps") or {}).keys())
    context_rows = []
    for row in rows:
        app = str(row.get("app") or "")
        context_rows.append({
            "row_id": row.get("row_id"),
            "app": app,
            "platform": row.get("platform"),
            "evidence_kind": row.get("kind"),
            "ua": row.get("ua"),
            "allowed_slot_paths": allowed_slot_paths(app) if app in app_keys else [],
            "app_version_build_history": (devices.get("meta", {}).get("apps", {}).get(app, {}) if app in app_keys else {}),
            "chrome_version": devices.get("meta", {}).get("versions", {}).get("chrome"),
        })
    prompt = {
        "task": "Normalize observed in-app User-Agent strings into reusable templates.",
        "rules": [
            "Return JSON only with a records array.",
            "Never invent tokens, token order, source evidence, app versions, app builds, device facts, or source row IDs.",
            "Use only the allowed_slot_paths for the row's app. Every placeholder must map to one listed path.",
            "If a value cannot be mapped, keep it literal in source_format, set template to null, and list the unresolved slot.",
            "Preserve the raw UA exactly; do not rewrite or normalize the observed string.",
            "Do not assume all Android in-app browsers use ; wv) or all iOS in-app browsers append an app marker.",
            "Do not infer Android logical density from physical PPI, SDK/API from OS version, or chipset from SoC marketing names.",
            "Do not combine rows from different apps, platforms, device variants, or format generations.",
            "Never return status verified. Return status pending only if the template is an exact structural match and all slots resolve; otherwise candidate.",
            "Return each source row at most once, identified by its exact row_id.",
        ],
        "output_schema": {
            "records": [{
                "row_id": "exact input row_id",
                "template": "normalized template string or null",
                "slots": {"placeholderName": "one exact allowed_slot_path"},
                "source_format": "raw format or source-derived format when template is null",
                "unresolved_slots": ["field names not resolvable from allowed paths"],
                "review_notes": ["source-grounded concerns only"],
            }]
        },
        "rows": context_rows,
    }
    body = json.dumps({
        "model": model,
        "messages": [{"role": "user", "content": json.dumps(prompt, ensure_ascii=False)}],
        "temperature": 0,
        "response_format": {"type": "json_object"},
    }).encode("utf-8")
    request = urllib.request.Request(API_URL, data=body, headers={
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    })
    with urllib.request.urlopen(request, timeout=120) as response:
        result = json.load(response)
    content = result["choices"][0]["message"]["content"]
    parsed = json.loads(content)
    if not isinstance(parsed, dict) or not isinstance(parsed.get("records"), list):
        raise ValueError("AI response must be a JSON object containing records[]")
    return parsed


def normalize_rows(
    source: dict[str, Any],
    devices: dict[str, Any],
    ai_result: dict[str, Any],
    fetched_at: str | None = None,
) -> tuple[dict[str, Any], dict[str, Any]]:
    app_keys = set((devices.get("meta", {}).get("apps") or {}).keys())
    rows = source.get("records", [])
    if not isinstance(rows, list):
        raise ValueError("decoded source records must be an array")
    by_id = {str(r.get("row_id")): r for r in rows if isinstance(r, dict) and r.get("row_id")}
    ai_rows = ai_result.get("records", [])
    seen: set[str] = set()
    normalized: list[dict[str, Any]] = []
    gaps: list[str] = []
    source_url_root = str(source.get("source_url") or "")
    source_id_root = str(source.get("source_id") or "useragent-in-inapp-corpus")
    capture_date = fetched_at or source.get("fetched_at") or datetime.now(timezone.utc).date().isoformat()
    try:
        date.fromisoformat(str(capture_date))
    except ValueError as exc:
        raise ValueError("source fetched_at must be YYYY-MM-DD") from exc

    for index, proposal in enumerate(ai_rows):
        if not isinstance(proposal, dict):
            gaps.append(f"AI record #{index} is not an object")
            continue
        row_id = str(proposal.get("row_id") or "")
        if not row_id or row_id not in by_id:
            gaps.append(f"AI returned unknown source row_id {row_id!r}; discarded")
            continue
        if row_id in seen:
            gaps.append(f"AI returned duplicate source row_id {row_id!r}; duplicate discarded")
            continue
        seen.add(row_id)
        raw = by_id[row_id]
        app = str(raw.get("app") or "")
        platform = str(raw.get("platform") or "")
        ua = str(raw.get("ua") or "")
        if app not in app_keys or platform not in {"android", "ios"} or not ua:
            gaps.append(f"Source row {row_id}: app/platform/raw UA missing or unsupported; discarded")
            continue
        source_url = str(raw.get("source_url") or source_url_root)
        if not source_url.startswith("https://"):
            gaps.append(f"Source row {row_id}: no HTTPS source URL; retained as source gap, not normalized")
            continue
        evidence_kind = str(raw.get("kind") or source.get("kind") or "")
        if evidence_kind not in validator.KINDS:
            gaps.append(f"Source row {row_id}: missing or unsupported source evidence kind; discarded")
            continue
        observed_at = raw.get("observed_at")
        if observed_at:
            try:
                date.fromisoformat(str(observed_at))
            except ValueError:
                gaps.append(f"Source row {row_id}: invalid observation date; discarded")
                continue

        slots = proposal.get("slots") if isinstance(proposal.get("slots"), dict) else {}
        template = proposal.get("template") if isinstance(proposal.get("template"), str) else None
        unresolved = proposal.get("unresolved_slots") if isinstance(proposal.get("unresolved_slots"), list) else []
        valid_slots = all(
            isinstance(name, str) and isinstance(path, str) and path in allowed_slot_paths(app)
            and validator.resolve_slot_path(path, app, devices)
            for name, path in slots.items()
        )
        matches = bool(template and validator.template_matches_observed(template, ua))
        if not valid_slots or not matches or unresolved:
            status = "candidate"
            source_format = str(proposal.get("source_format") or ua)
            template = None
            slots = {}
        else:
            status = "pending"  # AI cannot verify; human review + two-source validator required.
            source_format = None

        evidence = [{
            "source_id": str(raw.get("source_id") or source_id_root),
            "source_url": source_url,
            "source_row_id": row_id,
            "observed": ua,
            "quoted_text": str(raw.get("quoted_text") or ua),
            "app_version": raw.get("app_version"),
            "app_build": raw.get("app_build"),
            "observed_at": observed_at,
            "fetched_at": capture_date,
            "kind": evidence_kind,
        }]
        record = {
            "id": f"{app}-{platform}-{slug(row_id)}",
            "schemaVersion": 1,
            "app": app,
            "platform": platform,
            "status": status,
            "template": template,
            "source_format": source_format,
            "slots": slots,
            "unresolved_slots": unresolved if status == "candidate" else [],
            "compatibility": raw.get("compatibility") or {"minOS": None, "maxOS": None, "notes": ""},
            "evidence": evidence,
            "review_notes": list(proposal.get("review_notes") or []),
        }
        normalized.append(record)

    findings = {
        "schemaVersion": 1,
        "createdAt": datetime.now(timezone.utc).date().isoformat(),
        "sources": source.get("sources", []),
        "records": normalized,
        "collectionGaps": gaps,
    }
    summary = {
        "input_rows": len(rows),
        "ai_rows": len(ai_rows),
        "normalized_records": len(normalized),
        "pending": sum(1 for r in normalized if r["status"] == "pending"),
        "candidate": sum(1 for r in normalized if r["status"] == "candidate"),
        "gaps": gaps,
        "verified_promotions": 0,
    }
    return findings, summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, help="decoded source rows JSON")
    parser.add_argument("--devices", required=True, help="published devices.json, read-only")
    parser.add_argument("--out", required=True, help="normalized findings JSON")
    parser.add_argument("--summary", required=True, help="normalization summary JSON")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    args = parser.parse_args()
    key = os.environ.get("CEREBRAS_API_KEY")
    if not key:
        print("ERROR: CEREBRAS_API_KEY is not configured; no AI normalization was run.", file=sys.stderr)
        return 2
    try:
        source = json.loads(Path(args.input).read_text(encoding="utf-8"))
        devices = json.loads(Path(args.devices).read_text(encoding="utf-8"))
        ai_result = ai_request(source.get("records", []), devices, key, args.model)
        findings, summary = normalize_rows(source, devices, ai_result)
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(json.dumps(findings, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        Path(args.summary).parent.mkdir(parents=True, exist_ok=True)
        Path(args.summary).write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(summary, ensure_ascii=False, indent=2))
        return 0 if findings["records"] else 3
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
